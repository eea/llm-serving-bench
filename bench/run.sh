#!/usr/bin/env bash
# Run a benchmark sweep against a live vLLM OpenAI-compatible server and drop
# the raw JSONs into results/<date>_<model>_<tag>/.
#
#   bench/run.sh --model qwen3.6-27b-fp8 --label "Qwen 27B" \
#                --base-url http://localhost:9000 --served-model qwen/qwen3.6-27b
#
# The output file prefix is derived from --model, so a run can never be
# mislabelled the way the 2026-08-10 Gemma run was (every one of its files is
# named results_gpt_oss_120b_*.json because the script was copy-pasted).
#
# Flags: --model KEY --label NAME --base-url URL --served-model NAME
#        --prompts N --image IMAGE --tag LETTER
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(dirname "$HERE")"
# shellcheck source=sweep.env
source "$HERE/sweep.env"

MODEL="" LABEL="" TAG="a"
BASE_URL="${BASE_URL:-http://localhost:9000}"
SERVED_MODEL=""

while [[ $# -gt 0 ]]; do
        case "$1" in
                --model) MODEL="$2"; shift 2 ;;
                --label) LABEL="$2"; shift 2 ;;
                --base-url) BASE_URL="$2"; shift 2 ;;
                --served-model) SERVED_MODEL="$2"; shift 2 ;;
                --prompts) PROMPTS="$2"; shift 2 ;;
                --image) VLLM_IMAGE="$2"; shift 2 ;;
                --tag) TAG="$2"; shift 2 ;;
                -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
                *) echo "unknown argument: $1" >&2; exit 2 ;;
        esac
done

if [[ -z $MODEL ]]; then
        echo "--model is required (stable key, e.g. qwen3.6-27b-fp8)" >&2
        exit 2
fi
LABEL="${LABEL:-$MODEL}"
SERVED_MODEL="${SERVED_MODEL:-$MODEL}"
MODEL_SLUG="${MODEL//[!A-Za-z0-9]/_}"

# --- pick a free run directory --------------------------------------------
DATE="$(date +%F)"
RUN_DIR="$ROOT/results/${DATE}_${MODEL}_${TAG}"
while [[ -d $RUN_DIR && -n $(ls -A "$RUN_DIR" 2>/dev/null) ]]; do
        TAG="$(python3 - "$TAG" <<'PY'
import string, sys
t = sys.argv[1]
print(string.ascii_lowercase[(string.ascii_lowercase.index(t) + 1) % 26] if t in string.ascii_lowercase else t + "a")
PY
)"
        RUN_DIR="$ROOT/results/${DATE}_${MODEL}_${TAG}"
        echo "run dir taken, bumping tag -> $TAG"
done
mkdir -p "$RUN_DIR"
echo "run dir: ${RUN_DIR#"$ROOT"/}"

# --- capture the environment alongside the numbers ------------------------
{
        echo "# environment capture (generated by bench/run.sh)"
        echo "date: $(date -Is)"
        echo "client image: $VLLM_IMAGE"
        echo "base url: $BASE_URL"
        echo "served model: $SERVED_MODEL"
        echo "sweep: in=[$INPUT_LENS] out=[$OUTPUT_LENS] prompts=$PROMPTS"
        echo
        echo "## server model endpoint"
        curl -s --max-time 10 "$BASE_URL/v1/models" || echo "(server /v1/models unreachable)"
        echo
        echo "## nvidia-smi"
        nvidia-smi --query-gpu=index,name,memory.total,driver_version --format=csv || echo "(nvidia-smi unavailable on this host)"
        echo
        echo "## server container image (if running locally)"
        docker ps --format '{{.Names}}\t{{.Image}}' 2>/dev/null || echo "(docker unavailable)"
} >"$RUN_DIR/_env.txt"

# --- the sweep -------------------------------------------------------------
for IN in $INPUT_LENS; do
        for OUT in $OUTPUT_LENS; do
                OUT_FILE="results_${MODEL_SLUG}_in${IN}_out${OUT}.json"
                echo "==========================================================="
                echo "benchmark: in=$IN out=$OUT prompts=$PROMPTS  ->  $OUT_FILE"
                echo "server: $BASE_URL"
                echo "==========================================================="
                docker run --rm \
                        --network host \
                        --entrypoint="" \
                        -v "$RUN_DIR:/workspace" \
                        -w /workspace \
                        "$VLLM_IMAGE" \
                        vllm bench serve \
                        --base-url "$BASE_URL" \
                        --model "$SERVED_MODEL" \
                        --backend "$BACKEND" \
                        --dataset-name "$DATASET" \
                        --random-input-len "$IN" \
                        --random-output-len "$OUT" \
                        --num-prompts "$PROMPTS" \
                        --save-result \
                        --result-filename "$OUT_FILE"
        done
done

echo
echo "sweep complete: $(ls "$RUN_DIR"/*.json 2>/dev/null | wc -l) result files in ${RUN_DIR#"$ROOT"/}"
cat <<EOF

register the run, then regenerate the report:

  python3 analysis/register.py \\
      --dir results/$(basename "$RUN_DIR") \\
      --model $MODEL --label "$LABEL" \\
      --image $VLLM_IMAGE --gpu 'GPU 0' \\
      --notes 'describe anything unusual about this run'

  make ingest report figures verify
EOF
